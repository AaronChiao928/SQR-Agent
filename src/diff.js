// Difference report: the old Excel template vs the new rule layer, on the same rows.
//
// The parity test proves the old process was reproduced exactly. This report shows,
// row by row, where the new rules decide differently and why, using the evidence
// each side matched (which regex alternative in the old sheet, which list entry now).

import { legacyRow } from "./legacy.js";
import { applyRules } from "./rules.js";

const LEGACY_TO_NEW = { Brand: "brand", Competitor: "competitor", Generic: "none" };
const PRIORITY = ["brand", "competitor", "retailer"];

/** Which alternatives of an "a|b|c" pattern match the text (the old sheet's evidence). */
const legacyEvidence = (pattern, text) => pattern.split("|").filter((alt) => new RegExp(alt).test(text));

export function diffLegacyVsNew(fixture, profile) {
  const ctx = { brandPattern: fixture.brandPattern, competitorPattern: fixture.competitorPattern, existingKeywords: fixture.existingKeywords };
  const rows = fixture.rows
    .filter((r) => r.searchTerm && r.campaign && r.adGroup) // empty template rows are set aside by the input check
    .map((r) => ({ id: `R${r.excelRow}`, excelRow: r.excelRow, searchTerm: r.searchTerm, translation: r.translation, campaign: r.campaign, adGroup: r.adGroup, legacy: legacyRow(r, ctx) }));

  const res = applyRules(rows, profile);
  const byId = Object.fromEntries(res.rows.map((r) => [r.id, r]));

  const changes = [];
  const counts = {};
  for (const row of rows) {
    const n = byId[row.id];
    const newCats = PRIORITY.filter((c) => n.hits.some((h) => h.category === c));
    const newCat = newCats[0] ?? "none";
    const oldCat = LEGACY_TO_NEW[row.legacy.E];
    const k = `${oldCat} -> ${newCat}`;
    counts[k] = (counts[k] || 0) + 1;
    if (oldCat === newCat) continue;
    const oldEv =
      row.legacy.E === "Brand" ? legacyEvidence(fixture.brandPattern, row.translation)
      : row.legacy.E === "Competitor" ? legacyEvidence(fixture.competitorPattern, row.translation)
      : [];
    changes.push({
      excelRow: row.excelRow,
      searchTerm: row.searchTerm,
      translation: row.translation,
      old: oldCat,
      new: newCat,
      oldEvidence: oldEv,
      newEvidence: n.hits.filter((h) => h.category === newCat).map((h) => `${h.term} (${h.mode})`),
    });
  }

  // Campaign-type check. Old: column H (Brand/Generic of the term vs the ad group name).
  // New: the campaign name decides the type; a generic campaign is the expected home of a term with no list hit.
  const hOld = rows.filter((r) => r.legacy.H === "No Match");
  const hOldButGenericNoHit = hOld.filter((r) => byId[r.id].campaignType === "generic" && byId[r.id].hits.length === 0);
  const adGroupNaming = hOldButGenericNoHit.filter((r) => !/^(brand|generic)/i.test(r.legacy.G));

  return {
    rowsCompared: rows.length,
    counts,
    changes,
    campaignCheck: {
      legacyNoMatch: hOld.length,
      noLongerFlagged: hOldButGenericNoHit.length,
      ofWhichAdGroupNaming: adGroupNaming.length,
      adGroups: [...new Set(adGroupNaming.map((r) => r.adGroup))],
    },
    routing: {
      rules: res.rows.filter((r) => r.route === "rules").length,
      ai: res.aiQueue.length,
      notProcessed: res.notProcessed.length,
      negatives: res.negatives.length,
      flags: res.flags.length,
    },
  };
}

/** Render the report as Markdown (written to docs/reports/legacy-vs-new.md by the CLI). */
export function renderDiffMarkdown(d, source) {
  const L = [];
  L.push("# Legacy template vs new rule layer", "");
  L.push(`Generated by \`npm run diff\` from ${source}. Rows compared: ${d.rowsCompared} (empty template rows excluded).`, "");
  L.push("## 1. Term classification", "");
  L.push("Old: column E (regex on the machine translation). New: brand, competitor and retailer lists on the original term.", "");
  L.push("| Old -> New | Rows |", "|---|---|");
  for (const [k, v] of Object.entries(d.counts).sort((a, b) => b[1] - a[1])) L.push(`| ${k} | ${v} |`);
  L.push("", `Rows classified differently: ${d.changes.length}`, "");
  L.push("| Row | Search term | Translation | Old | New | Old evidence | New evidence |", "|---|---|---|---|---|---|---|");
  for (const c of d.changes)
    L.push(`| ${c.excelRow} | ${c.searchTerm} | ${c.translation} | ${c.old} | ${c.new} | ${c.oldEvidence.join(", ") || "-"} | ${c.newEvidence.join(", ") || "-"} |`);
  L.push("", "## 2. Campaign-type check", "");
  L.push(`Old column H flagged ${d.campaignCheck.legacyNoMatch} rows as No Match. ` +
    `${d.campaignCheck.noLongerFlagged} of them are terms with no brand, competitor or retailer hit in a campaign named as generic, ` +
    `so the new rules treat them as being in the right campaign type and pass them to the AI for the product-relevance check. ` +
    `${d.campaignCheck.ofWhichAdGroupNaming} of these were flagged only because the ad group name does not start with "brand_" or "generic_":`, "");
  for (const a of d.campaignCheck.adGroups) L.push(`- \`${a}\``);
  L.push("", "## 3. Where rows go next", "");
  L.push(`| Route | Rows |`, `|---|---|`);
  L.push(`| Handled by rules | ${d.routing.rules} |`, `| Sent to the AI (stage 3) | ${d.routing.ai} |`, `| Not processed (out of scope) | ${d.routing.notProcessed} |`);
  L.push("", `Rule-based negative suggestions after de-duplication: ${d.routing.negatives}. Flags for disabled rules: ${d.routing.flags}.`, "");
  return L.join("\n");
}
